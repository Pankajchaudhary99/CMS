package org.example;

public class User {

    private String name;
    private String job;
    private String email;

    public void setEmail(String email){
        this.email = email;
    }

    //setter and getter
    public void setName(String name){
        this.name = name;
    }

    public String getName(){
        return name;
    }

    public void setJob(String job){
        this.name = name;
    }

    public String getJob(){
        return job;
    }

}
